/* The two-channel model as a scenario, held to the model it claims to be.

   docs/bench/demo/purpose-two-channel.amg.json is generated by
   scripts/make_two_channel_scenario.mjs, and a generated scenario is a
   declaration about a model: these are the ways it could say something the
   model does not.

   What is asserted here needs no browser. That the bench can OPEN it -- that
   the eleven mechanisms arrive as relations, that nothing is missing, that the
   declared class is the hundred combinations and that the derivation runs --
   is tests/scenario-twochannel.mjs, which drives the real page.

   The sharpest assertion is the third: the scenario's arithmetic, evaluated
   line by line, gives the same four outcomes as the grammar it was written
   from. A scenario that drifted from the model would still look like a
   scenario, and nothing else here would notice.
*/

import { test } from "node:test";
import assert from "node:assert/strict";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import * as K from "../docs/bench/core/kernel.js";
import { CENTRE, MODEL, META, VOCAB, combinations, familyOf, makeRun,
  defaultForms } from "../scripts/two-channel-run.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const read = p => JSON.parse(fs.readFileSync(join(here, "..", p), "utf8"));
const SCEN = read("docs/bench/demo/purpose-two-channel.amg.json");
const SCOPE = read("docs/showcase-a/scope.json");
const SN = SCEN.snap;
/* The corpus payload, parsed out of the one-line module the page loads. Read
   lazily: only the threshold test needs it, and it is 1.6 MB. */
let NODES = null;
function nodes(){
  if(NODES) return NODES;
  const src = fs.readFileSync(join(here, "..", "docs", "bench", "graph-data.js"), "utf8");
  const one = src.slice(0, src.indexOf("\n"));
  NODES = JSON.parse(one.slice(one.indexOf("{"), one.lastIndexOf("}") + 1)).nodes;
  return NODES;
}
const A = SN.arith;

/* The scenario's own arithmetic, evaluated: every line parsed in order against
   the scope its declarations give, which is what the page does. */
function runScenario(params){
  const consts = new Map(A.consts.map(c => [c.name, c.value]));
  const scope = new Set([...SN.vtype.filter(v => v.bset).map(v => v.name), ...consts.keys()]);
  const V = Object.create(null);
  Object.assign(V, Object.fromEntries(consts), params);
  for(const ln of A.lines){
    const e = K.readExpr(ln.py, scope);
    scope.add(ln.lhs);
    V[ln.lhs] = K.evalRPN(e.rpn, V);
  }
  return V;
}

test("it is a scenario file this bench reads", () => {
  assert.equal(SCEN.format, "amg-scenario");
  assert.equal(SCEN.v, 1);
  assert.ok(SCEN.bench && SCEN.bench.v, "unstamped bench");
  assert.ok(SCEN.corpus && SCEN.corpus.commit, "unstamped corpus");
  assert.equal(typeof SN.stage, "number");
  assert.ok(SN.stage >= 1);
  /* Nothing is claimed about the invariants or the staleness of the body: the
     page computes both, and a generator writing either would be writing a
     result nobody produced. */
  assert.equal(A.run, null, "the generator must not report invariant verdicts");
  assert.equal(A.sig, "", "an invented signature would read as a checked one");
  assert.deepEqual(SN.board, {rows: [], seq: 0}, "nothing is retained for the reader");
});

test("the declarations are the model's own, and complete", () => {
  const params = SN.vtype.filter(v => v.bset).map(v => v.name);
  const outs = SN.vtype.filter(v => !v.bset).map(v => v.name);
  /* A quantity is a parameter only if some mechanism reads it: a name no
     relation carries is a name the arithmetic cannot use. */
  for(const p of params)
    assert.ok(SN.mclm.some(m => m.from === p), `nothing carries ${p}`);
  for(const o of outs)
    assert.ok(SN.mclm.some(m => m.to === o), `nothing writes ${o}`);
  assert.equal(SN.mclm.length, META.mechanisms.length);
  for(const m of SN.mclm){
    const mech = META.mechanisms.find(x => x.id === m.name);
    assert.ok(mech, `${m.name} is not a mechanism of this model`);
    assert.ok(mech.reads.includes(m.from), `${m.name} does not read ${m.from}`);
    const writes = mech.writes.map(w => MODEL.outcome_names[m.to] === w ? m.to : null);
    assert.ok(writes.some(Boolean), `${m.name} does not write ${m.to}`);
    /* The role is the model's and the sign is not invented from it: two of the
       six roles fix a direction and the rest leave it undeclared. */
    const sp = SN.spec.find(([k]) => k === "mx:" + m.id);
    assert.ok(sp, `${m.name} carries no declarations`);
    assert.deepEqual(sp[1].roles, [mech.role]);
    assert.ok(VOCAB.roles.some(r => r[0] === mech.role), `${mech.role} is not a role`);
    if(mech.role === "dissipates") assert.equal(m.g, "negative");
    if(mech.role === "modulates" || mech.role === "allocates") assert.equal(m.g, "");
  }
  /* Every parameter no mechanism reads is pinned as a constant, at the point
     the published figures were drawn at. */
  for(const [k, v] of Object.entries(MODEL.parameters)){
    if(params.includes(k)) continue;
    const c = A.consts.find(x => x.name === k);
    assert.ok(c, `${k} is neither a parameter nor a constant`);
    assert.equal(c.value, CENTRE[k], `${k} is pinned away from the figures' point`);
    assert.ok(v, "and the model declares a range for it");
  }
});

test("the arithmetic is the model: the same four outcomes, to the last digit", () => {
  /* The lines are the grammar's, so this is a check that the scenario carries
     them unaltered -- the tagging (term, out, local, which class) is where a
     generator can go wrong without changing a single expression. */
  const run = makeRun(combinations().find(c => Object.entries(defaultForms())
    .every(([slot, member]) => c.members[slot][0] === member)));
  const at = {...CENTRE, pi: 0.37};
  const want = run(at);
  const got = runScenario(at);
  for(const [low, up] of Object.entries(MODEL.outcome_names)){
    if(!(low in got)) continue;
    assert.ok(Number.isFinite(got[low]), `${up} is not a number`);
    assert.equal(got[low], want[low], `${up} differs from the grammar`);
  }
  assert.equal(A.lines.filter(l => l.kind === "term").length, META.mechanisms.length);
  assert.equal(A.lines.filter(l => l.kind === "out").length, 4);
  for(const l of A.lines.filter(l => l.kind === "term"))
    assert.ok(META.mechanisms.some(m => m.id === l.mech),
      `${l.lhs} names ${l.mech}, which is not a mechanism`);
});

test("three classes on the lines several mechanisms read, and they are the hundred", () => {
  const declared = A.lines.filter(l => l.family);
  assert.deepEqual(declared.map(l => l.lhs), ["eff", "sat", "cvx"]);
  let product = 1;
  for(const l of declared){
    const f = familyOf(l.family);
    assert.ok(f, `${l.family} is not a family`);
    assert.ok(f.members.some(m => m[0] === l.member),
      `${l.family} has no member ${l.member}`);
    product *= f.members.length;
    /* The class sits on a line, not on a mechanism's term, which is the whole
       reason this scenario could not exist before: several mechanisms read
       each of these three. */
    assert.equal(A.lines.filter(x => x.kind === "term" && x.py.includes(l.lhs)).length > 0,
      true, `nothing reads ${l.lhs}`);
  }
  assert.equal(product, SCOPE.grid.forms,
    "the declared class is not the hundred combinations scope.json reports");
  /* And no mechanism term carries a class of its own, because its expression
     is arithmetic over these three rather than a curve from its antecedent. */
  for(const l of A.lines.filter(l => l.kind === "term"))
    assert.equal(l.family, undefined, `${l.lhs} declares a shape class as well`);
});

test("the baseline block is zero whichever member is picked", () => {
  /* eff_0 and sat_0 are the credibility and saturating curves written at
     pi = 0, and they carry no declared class. They do not need one: every
     member of every family has f(0)=0, so both are zero whatever the class
     run substitutes, and the baseline the outcomes are differences from does
     not move with the shape. This is asserted rather than reasoned about,
     because if it were false the class run would be enumerating models whose
     live curve and baseline curve disagree. */
  for(const combo of combinations()){
    const run = makeRun(combo);
    const V = run({...CENTRE, pi: 0.5});
    assert.equal(V.eff_0, 0, `eff_0 is ${V.eff_0} at ${combo.label}`);
    assert.equal(V.sat_0, 0, `sat_0 is ${V.sat_0} at ${combo.label}`);
  }
});

test("the literature behind the model is curated, not absent", () => {
  /* A scenario carrying no journals and no merges, opening on the model,
     gives a reader a closed model with no account of where any of it came
     from: the two-channel model cannot be built in the void. The vocabulary was in the corpus all along -- Stoelhorst and
     Vishwanathan is paper 022 of the 52 -- and what was missing is that the
     scenario pointed at none of it. */
  assert.equal(SN.jr.length, 12, "the outlet frame is not declared");
  assert.equal(SN.minp, 2, "the threshold moved, where a named exception was the point");
  assert.ok(SN.groups.length >= 3, "no merge is recorded, so nothing was selected");
  assert.equal(SN.stage, 1, "it still opens past the curation it now carries");
  assert.equal(SN.mcon.length, SN.vtype.length,
    "every quantity is declared as a construct and typed");
});

test("a construct below the threshold is admitted by name, never by moving it", () => {
  /* Six of the constructs this model is about are carried by one paper each.
     Lowering the threshold to one would admit 660 constructs to reach six, so
     each is admitted by name instead: a named exception a reader can refuse,
     rather than a global loosening nobody can audit. */
  assert.ok(SN.admit.length >= 5, "nothing is admitted below the threshold");
  const NODES = new Map(nodes().map(n => [n.i, n]));
  for(const id of SN.admit){
    const n = NODES.get(id);
    assert.ok(n, `${id} is admitted and the corpus does not carry it`);
    assert.ok(n.n < SN.minp,
      `${id} is admitted by name and is already in scope at ${SN.minp} papers`);
  }
  /* And the admitted ones are the rights vocabulary, which is what makes the
     exception about this model rather than a convenience. */
  for(const id of ["shirking-vulnerability", "control-rights-allocation"])
    assert.ok(SN.admit.includes(id), `${id} is not admitted, so the model reads a construct out of scope`);
});

test("a merge that reduces four distinctions to one says so", () => {
  /* Stoelhorst and Vishwanathan cross four vulnerabilities on two dimensions
     and keep them apart deliberately. This model needs one exposure, so they
     are merged, and that is the reduction a reader is most likely to refuse.
     It is a declared merge with a name on it rather than an arithmetic that
     quietly adds them. */
  const g = SN.groups.find(x => x.members.includes("shirking-vulnerability"));
  assert.ok(g, "the vulnerabilities are not merged anywhere");
  for(const v of ["holdup-vulnerability", "market-power-vulnerability",
    "externality-vulnerability"])
    assert.ok(g.members.includes(v), `${v} is outside the merge that claims to carry it`);
});

test("the second literature is joined, and each join has a member from both", () => {
  /* A merge whose members come from one literature is a merge; one whose
     members come from two IS the join, which is the whole of what step 2.1
     produces. A join with both members on one side would be step 1.2 wearing
     step 2.1's name. */
  const L = SN.lits;
  assert.ok(L && L.list && L.list.length === 1, "no second literature travels with the scenario");
  const gov = L.list[0];
  assert.equal(gov.base.format, "amg-stream");
  assert.equal(gov.dec.minp, 1,
    "the second literature is scoped at the first one's threshold, not on its own terms");
  const side = new Map([
    ...SN.groups.flatMap(g => g.members).map(m => [m, "purpose"]),
    ...gov.base.constructs.map(c => [c.id, "governance"]),
  ]);
  /* Carried-but-unmerged purpose constructs count as purpose too. */
  for(const c of SN.mcon) if(!side.has(c.id)) side.set(c.id, "model");
  assert.ok(L.joins.groups.length >= 2, "nothing was joined across the two");
  for(const j of L.joins.groups){
    const sides = new Set(j.members.map(m => side.get(m) || "purpose"));
    assert.ok(sides.has("governance"),
      `${j.id} is called a join and names nothing from the second literature`);
    assert.ok(sides.size > 1, `${j.id} joins one literature with itself`);
  }
});

test("a quantity no paper carries says so, in the definition a reader sees", () => {
  /* What the model ADDS is said explicitly, as a declared construct.
     Three registers: read off the purpose corpus, read off the literature
     joined at 2.1, or carried by nobody. AI intensity is the third, and for an
     AI-themed model that is the interesting admission rather than an
     embarrassment. */
  const by = id => (SN.mcon.find(c => c.id === id) || {}).def || "";
  assert.match(by("pi"), /Read off the purpose literature/);
  assert.match(by("principal_conflict"), /second literature joined at step 2\.1/);
  assert.match(by("b"), /Joined at step 2\.1 across both literatures/);
  assert.match(by("alpha"), /DECLARED BY THIS MODEL, and carried by no paper/);
  /* And no quantity is left without an account of itself. */
  for(const c of SN.mcon)
    assert.ok(/Read off|Joined at|DECLARED BY THIS MODEL/.test(c.def),
      `${c.id} does not say where it came from`);
});

test("the reconstructed margin is a declaration, never a claim", () => {
  /* The fixed-residual margin is read as a degree so a model can move between
     the channels. Stoelhorst and Vishwanathan state the distinction and not
     the quantity, so writing it as a claim would put words in their paper. It
     sits in the stream's declarations, where what a modeller added lives. */
  const gov = SN.lits.list[0].base;
  const c = gov.constructs.find(x => x.id === "fixed-control-rights-share");
  assert.ok(c, "the margin is not in the second literature at all");
  assert.deepEqual(c.papers, [], "the reconstructed margin is attributed to a paper");
  assert.match(c.definition, /RECONSTRUCTED/);
  assert.ok(!gov.claims.some(x =>
    x.antecedent.includes(c.id) || x.consequent.includes(c.id)),
    "a reconstructed quantity appears in a claim, which attributes it to a paper");
  assert.ok((gov.declarations || []).some(d => d.quantity === c.id),
    "the margin is reconstructed and is not recorded as a declaration");
});
