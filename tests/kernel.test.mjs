/* The grammar, against Python, and against its own refusals.

   Until this file existed the only automated check on the bench was that its
   scripts parsed. The claim under test is that 28 expressions evaluate identically
   in the page's walker and in Python, and that 8 malformed ones are refused
   with a specific reason each. The claim was measured once and recorded in
   prose. Here it is as a test.

   `kernel_expected.json` holds Python's own answer for each expression,
   generated by `kernel_cases.py`. Regenerate it when the cases change; do not
   edit it by hand, or the cross-language claim becomes a claim about this file.

   Run: node --test artifact/tests/
*/
import { test } from "node:test";
import assert from "node:assert/strict";
import * as K from "../docs/bench/core/kernel.js";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const EXPECTED = JSON.parse(readFileSync(join(here, "kernel_expected.json"), "utf8"));

const scope = new Set(Object.keys(EXPECTED.scope));

test("the module loads outside a browser, and carries both halves", () => {
  /* The grammar came out first and the calculus followed, so this names both
     rather than a count: a count tells you something moved and not what. */
  for (const n of ["ATOK", "ANAME", "APREC", "ANARY", "ARIGHT", "readExpr", "evalRPN"])
    assert.ok(n in K, `the grammar is missing ${n}`);
  for (const n of ["NUM", "VAR", "OP", "NEG", "FN", "hasVar", "rpnTree", "dTree",
                   "simp", "treeText", "ivalTree", "IBAD", "proveSign", "locateFlip",
                   "mmResolve", "treeNames"])
    assert.ok(n in K, `the calculus is missing ${n}`);
  for (const n of ["treeHTML", "exportSympy", "inlineOutcome", "PROPS"])
    assert.ok(!(n in K), `${n} touches the page and should have stayed in it`);
});

test(`${EXPECTED.valid.length} expressions mean the same thing in JavaScript and Python`,
  () => {
    for (const c of EXPECTED.valid) {
      const e = K.readExpr(c.src, scope);
      const got = K.evalRPN(e.rpn, EXPECTED.scope);
      assert.ok(Number.isFinite(got), `${c.src} did not evaluate to a number`);
      /* Relative, because `a ** b ** c` is 2 ** 9 and an absolute epsilon that
         suits 0.5 says nothing there. */
      const tol = Math.max(1e-12, Math.abs(c.py) * 1e-12);
      assert.ok(Math.abs(got - c.py) <= tol,
        `${c.src}\n  javascript ${got}\n  python     ${c.py}`);
    }
  });

test("every expression reports the names it reads", () => {
  const e = K.readExpr("min(a, b) + k_clarity * 2", scope);
  assert.deepEqual([...e.uses].sort(), ["a", "b", "k_clarity"]);
  assert.equal([...K.readExpr("0.5 + 1", scope).uses].length, 0);
});

test(`${EXPECTED.refused.length} malformed expressions are refused, each by name`, () => {
  for (const c of EXPECTED.refused) {
    let msg = null;
    try { K.readExpr(c.src, scope); }
    catch (err) { msg = err.message; }
    assert.ok(msg !== null, `"${c.src}" was accepted and should not have been`);
    assert.ok(msg.includes(c.says),
      `"${c.src}" was refused, but for the wrong reason\n  said:   ${msg}\n  wanted: ${c.says}`);
  }
});

test("a line past the 400-character cap is refused for being long, not for a token", () => {
  const c = EXPECTED.too_long;
  assert.throws(() => K.readExpr(c.src, scope), e => e.message.includes(c.says));
});

test("a doubled sign is a unary operator, not a typo to guess at", () => {
  for (const c of EXPECTED.tolerated) {
    const e = K.readExpr(c.src, scope);
    const got = K.evalRPN(e.rpn, EXPECTED.scope);
    assert.ok(Math.abs(got - c.py) <= 1e-12, `${c.src}: ${got} vs python ${c.py}`);
  }
});

test("the walker needs no eval and touches no DOM", () => {
  const src = readFileSync(join(here, "..", "docs", "bench", "core", "kernel.js"), "utf8");
  for (const bad of ["eval(", "new Function", "document.", "window."])
    assert.ok(!src.includes(bad), `kernel.js contains ${bad}`);
  /* It is 26KB now rather than 5, and the property that let both halves move is
     the one most easily lost by a later edit, so the check covers all of it. */
  assert.ok(src.length > 20000, "the calculus does not look like it came across");
});
