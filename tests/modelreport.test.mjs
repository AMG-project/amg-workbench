/* docs/bench/model-report.js is generated, and this is what keeps it honest.

   The file is what the model returned: the declared classes, the nine
   conclusions with the members that break them, the margins, and -- the half
   this test cannot check -- what the corpus has behind each relation, which
   comes from ../purpose-review and is not part of this repository.

   For a while it was a frozen artefact with no producer at all: P6 removed
   drystone and took `scripts/export_bench_model.py` with it, so a
   committed 22KB file named a script nobody had, and a rebuilt corpus would
   not have reached it. The producer is back, over the grammar instead of the
   engine. What this test asserts is that the committed file is what the
   producer produces -- the model half of it, which needs nothing outside this
   repository -- so it cannot quietly drift from the model it reports on.

   The corpus half's own guard is in the exporter: a binding to an id that is
   not in the registry stops the build.
*/

import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import fs from "node:fs";

const here = dirname(fileURLToPath(import.meta.url));
const ART = join(here, "..");
const FILE = join(ART, "docs", "bench", "model-report.js");

const SRC = fs.readFileSync(FILE, "utf8");
const COMMITTED = (() => {
  const i = SRC.indexOf("const MR=") + "const MR=".length;
  return JSON.parse(SRC.slice(i, SRC.indexOf(";\n", i)));
})();

/* The producer, run. Spawned rather than imported because it is a command: if
   `node scripts/model_report.mjs` stops working, this has to fail. */
const FRESH = (() => {
  const r = spawnSync(process.execPath, [join("scripts", "model_report.mjs")],
    {cwd: ART, encoding: "utf8"});
  assert.equal(r.status, 0, `model_report.mjs failed:\n${r.stderr}`);
  return JSON.parse(r.stdout);
})();

test("the committed model half is what the producer produces", () => {
  assert.deepEqual(FRESH.model, COMMITTED.model);
});

test("every conclusion in the file is the conclusion the model reaches now", () => {
  assert.deepEqual(FRESH.conclusions.map(c => c.id), COMMITTED.conclusions.map(c => c.id),
    "the nine, in the order the model declares them");
  for(const got of FRESH.conclusions){
    const was = COMMITTED.conclusions.find(c => c.id === got.id);
    /* Field by field, because `deepEqual` on the pair would say "objects
       differ" about a margin that moved in the sixth decimal and about a
       conclusion that stopped holding, and those are not the same news. */
    for(const k of ["text", "survives", "of", "breaks", "margin"])
      assert.deepEqual(got[k], was[k], `${got.id}.${k}`);
  }
});

test("the relations carry the mechanism metadata the model declares", () => {
  /* The corpus half cannot be recomputed here, but the model's own half of
     each relation can: a mechanism whose documentation moves and whose report
     does not is a relation described one way and adjudicated another. */
  const META = JSON.parse(fs.readFileSync(
    join(ART, "models", "purpose-two-channel-meta.json"), "utf8"));
  assert.equal(COMMITTED.relations.length, META.mechanisms.length);
  for(const [i, m] of META.mechanisms.entries()){
    const r = COMMITTED.relations[i];
    for(const k of ["id", "says", "reads", "writes", "role"])
      assert.deepEqual(r[k], m[k], `relation ${i} (${m.id}).${k}`);
  }
});

test("the file is still a module, and says it was generated", () => {
  /* The emitter predates the conversion and wrote no export line, so a
     regenerated copy would have taken every panel that reads MR off the page.
     Both halves of that are asserted: the page needs the export, and a reader
     needs to be told not to edit the file by hand. */
  assert.match(SRC, /^\/\* Generated by scripts\/export_bench_model\.py/);
  assert.match(SRC, /export \{ MR \};\s*$/);
  assert.ok(/models\/purpose-two-channel\.json/.test(SRC),
    "the header should name what the model half is built from");
});
